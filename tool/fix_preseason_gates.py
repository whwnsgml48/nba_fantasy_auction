#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""드래프트 당일 **관측 불가능한 조건**을 실행 조건에서 걷어낸다 (40차).

문제
  드래프트는 **2026-09-05** 다. 프리시즌 시작은 그로부터 **31일 뒤**(2026-10-06쯤),
  훈련캠프도 **24일 뒤**(2026-09-29쯤)다. 그런데 실행 조건 여러 곳이
  「프리시즌에 확인되면」에 걸려 있었다.

  가장 심한 것이 c5 다. 판단표에서 c5 를 여는 게이트가 **그것 하나뿐**이고
  (39차에 가격 게이트를 동어반복이라며 제거했다), 그 하나가 드래프트 당일 관측
  불가능하다 → **c5 는 자기 게이트로는 영원히 열리지 않는다.**

  `draft_date.note` 에 「문서의 '개막 1~2주 전' 가정은 틀렸다」고 **이미 적혀 있었다.**
  사실은 기록됐는데 그 사실에 의존하는 문장들이 안 고쳐졌다 — 이 저장소가 반복하는 형태다.

무엇으로 바꾸는가
  2026-09-05 에 **실제로 볼 수 있는 것**만 남긴다:
    · 구단·선수 공식 발표와 보도 기준 복귀 일정
    · 드래프트 당일 야후 부상 표기(OUT / IL 지정 여부)
    · 방 안의 실제 낙찰가 — 시장이 그를 어떻게 값매기는가
  「실경기로 확인」은 드래프트 후에만 가능하므로 **사후 갱신 항목**으로 따로 옮긴다.

무엇을 바꾸지 않는가
  「작년 낙찰가는 프리시즌 기대치다」류의 **서술**은 그대로 둔다. 이건 조건이 아니라
  과거 사실 설명이다. 조건과 서술을 구분하지 않고 문자열을 일괄치환하면 근거가 망가진다.
"""
import json, io, os

BASE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CP = BASE + "/data/cores.json"

OBSERVABLE = ("드래프트 당일(2026-09-05)에 볼 수 있는 것만으로 판정한다 — "
              "구단·선수 공식 발표와 보도 기준 복귀 일정 · 야후 부상 표기(OUT/IL) · 방 안의 실제 낙찰가. "
              "프리시즌 시작은 31일 뒤라 실경기 확인은 불가능하다.")


def main():
    cj = json.load(io.open(CP, encoding="utf-8"))
    n = 0

    d5 = next(d for d in cj["decision_table"] if d["core"] == "c5")
    d5["label"] = "Sabonis 복귀 일정이 개막 전으로 보도되고, 방에서 실제로 할인될 때"
    d5["cond"]["desc"] = ("드래프트 당일 기준 ① Sabonis 가 야후에서 OUT/IL 로 표기돼 있지 않고 "
                          "② 구단·보도 기준 복귀 일정이 개막(2026-10-20) 전이며 "
                          "③ 방에서 실제 낙찰가가 $26 이하로 흐를 때")
    d5["cond"]["observable_at_draft"] = OBSERVABLE
    d5["cond"]["removed_price_gate"]["real_condition"] = (
        "드래프트 당일 관측 가능한 복귀 정보 + 방 안의 실제 가격 (cond.desc)")
    d5["cond"]["removed_price_gate"]["superseded_40"] = (
        "39차에 「프리시즌 정상 복귀 확인」을 실질 조건으로 남겼는데 그건 드래프트 31일 뒤에나 "
        "관측 가능하다 — 남은 게이트가 그것 하나였으므로 c5 는 열릴 수 없는 플랜이었다. "
        "가격 조건을 되돌린 것이 아니라, **관측 가능한 조건으로 다시 쓴 것**이다.")
    n += 1

    c5 = next(c for c in cj["cores"] if c["id"] == "c5")
    c5["premise"] = ("⚠️ 격리된 별도 베팅안. **드래프트 당일 관측 가능한 것으로만 판정한다** — "
                     "복귀 일정 보도와 야후 부상 표기, 그리고 방 안의 실제 가격. 프리시즌 실경기는 "
                     "드래프트 31일 뒤라 조건으로 쓸 수 없다. 실출장 ~20경기이고 A/T 한계기여는 "
                     "−0.102로 마이너스 — 정상 복귀를 기본값으로 두면 위험합니다. 헤지 빅 2명을 필수로 붙입니다.")
    n += 1

    cj["league_rules_confirmed"]["sabonis_haliburton"]["caveat"] = (
        "측정이 아니라 기대다. ⚠️ **드래프트(2026-09-05) 시점에는 실경기로 확인할 방법이 없다** — "
        "프리시즌은 31일 뒤다. 근거 교체는 드래프트 후에만 가능하므로 이 값은 드래프트 내내 "
        "'기대' 등급으로 남는다.")
    n += 1

    c2 = next(c for c in cj["cores"] if c["id"] == "c2")
    if "jokic_gp_sensitivity_39" in c2:
        c2["jokic_gp_sensitivity_39"]["decision"] = c2["jokic_gp_sensitivity_39"]["decision"].replace(
            "드래프트 당일 Jokić 의 프리시즌 상태가 나쁘면 c2 를 1위로 읽지 말 것.",
            "드래프트 당일 Jokić 의 복귀·컨디션 **보도**가 나쁘면 c2 를 1위로 읽지 말 것 "
            "(프리시즌 실경기는 드래프트 31일 뒤라 볼 수 없다).")
        n += 1

    c3 = next(c for c in cj["cores"] if c["id"] == "c3")
    h = (c3.get("gp_hedge_39") or {}).get("lillard")
    if h and "드래프트 직전 프리시즌 출장" in h:
        c3["gp_hedge_39"]["lillard"] = h.replace(
            "드래프트 직전 프리시즌 출장 여부를 반드시 확인하고",
            "드래프트 당일 야후 부상 표기와 구단·보도 기준 복귀 일정을 반드시 확인하고 "
            "(프리시즌 출장은 드래프트 31일 뒤라 볼 수 없다)")
        n += 1

    cj["decision_strength_notes"]["c5"] = (
        "⚠ 가정 **둘**을 동시에 얹는다 — Hali GP 73 + Sabonis 복귀. GP 54면 78.8%로 최하위. "
        "발동 조건은 드래프트 당일 볼 수 있는 것(복귀 보도 · 부상 표기 · 방 안 실제 가격)으로만 판정한다")

    cj["observability_rule_40"] = {
        "draft_date": "2026-09-05",
        "preseason_starts_about": "2026-10-06 (드래프트 +31일)",
        "training_camp_about": "2026-09-29 (드래프트 +24일)",
        "season_opens": "2026-10-20 (드래프트 +45일)",
        "rule": ("실행 조건(판단표 label · cond.desc · premise · 헤지 절차)은 **드래프트 당일에 "
                 "관측 가능한 사건만** 참조한다. 「프리시즌에 확인되면」·「실경기로 확인」은 "
                 "조건이 아니라 **사후 갱신 항목**이다."),
        "why": ("c5 의 게이트가 그것 하나였고 드래프트 31일 뒤에나 관측 가능해서 **열릴 수 없는 "
                "플랜**이 돼 있었다. `draft_date.note` 에 날짜 사실은 이미 적혀 있었는데 그 사실에 "
                "의존하는 문장들이 안 고쳐진 것이 원인이다."),
        "scope": ("서술은 대상이 아니다 — 「작년 낙찰가는 프리시즌 기대치다」는 과거 사실 설명이지 "
                  "조건이 아니다. 문자열 일괄치환을 하면 근거가 망가진다."),
    }

    json.dump(cj, io.open(CP, "w", encoding="utf-8"), ensure_ascii=False, indent=1)
    print("관측 불가 조건 %d곳 재작성 · observability_rule_40 기록" % n)


if __name__ == "__main__":
    main()
